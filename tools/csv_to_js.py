#!/usr/bin/env python3
"""Turn a keys CSV into a JavaScript data file that adds rows to KEYS.

Usage:
    python3 tools/csv_to_js.py data/toyota-keys.csv keys-toyota.js

Then add <script src="keys-toyota.js"></script> to index.html (after keys.js).

Only the compatibility fields go into the generated file:
make, model, yearFrom, yearTo, keyType, chip, fcc, board, partNumber, programming, verified.
"board" is read as text so codes like 0020 keep their leading zeros.
Supplier names, SKUs, supply types, notes and sources are left out on purpose.
Rows that are identical once those are left out are folded into one.

It refuses to write anything if a row looks wrong, and it never changes
"verified" to true.
"""
import csv
import json
import sys

ALLOWED_PROGRAMMING = {"DIY", "Locksmith", "Dealer only", "Unconfirmed"}
REQUIRED = ["make", "model", "yearFrom", "yearTo", "keyType"]


def main(csv_path, out_path):
    with open(csv_path, encoding="utf-8-sig", newline="") as f:
        rows = list(csv.DictReader(f))

    problems = []
    entries = []
    seen = set()
    duplicates = 0
    for n, r in enumerate(rows, start=2):  # line 1 is the header
        r = {k: (v or "").strip() for k, v in r.items()}
        for field in REQUIRED:
            if not r.get(field):
                problems.append(f"line {n}: missing {field}")
        if not (r["yearFrom"].isdigit() and r["yearTo"].isdigit()):
            problems.append(f"line {n}: years must be numbers")
            continue
        yf, yt = int(r["yearFrom"]), int(r["yearTo"])
        if yf > yt:
            problems.append(f"line {n}: yearFrom {yf} is after yearTo {yt}")
        if r["programming"] not in ALLOWED_PROGRAMMING:
            problems.append(f"line {n}: programming '{r['programming']}' not allowed")
        board = r.get("board", "")
        if board and not (len(board) == 4 and board.isdigit()):
            print(f"  note: line {n}: board '{board}' is not a 4-digit number (kept as is)")

        entry = {
            "make": r["make"],
            "model": r["model"],
            "yearFrom": yf,
            "yearTo": yt,
            "keyType": r["keyType"],
            "chip": r.get("chip", ""),
            "fcc": r.get("fcc", ""),
            "board": r.get("board", ""),
            "partNumber": r.get("partNumber", ""),
            "programming": r["programming"],
            "verified": False,  # always false until you test it on a real vehicle
        }
        fingerprint = json.dumps(entry, sort_keys=True)
        if fingerprint in seen:
            duplicates += 1
            continue
        seen.add(fingerprint)
        entries.append(entry)

    if problems:
        print("Nothing written. Fix these first:")
        for p in problems:
            print("  " + p)
        sys.exit(1)

    lines = [
        "// Generated by tools/csv_to_js.py. Do not edit by hand.",
        "// Edit the source CSV and run the script again.",
        "// Every row here is verified: false.",
        "KEYS.push(",
    ]
    lines += ["  " + json.dumps(e, ensure_ascii=False) + "," for e in entries]
    lines.append(");")
    with open(out_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print(f"Read {len(rows)} rows, folded {duplicates} identical ones, wrote {len(entries)} to {out_path}")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
